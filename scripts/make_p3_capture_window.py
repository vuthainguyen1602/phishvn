#!/usr/bin/env python3
"""
make_p3_capture_window.py — when the 1,919 pages of the pinned content corpus were captured.

WHY. Section 7 of the P3 article calls the paired page corpus a narrow-window snapshot and gives
monthly counts. Until 2026-10-03 those counts (1,277 July, 417 August, a 73-page tail) were typed
by hand on 2026-08-18 from a manifest that has since been rebuilt, so they summed to 1,767 pages
while Table 2 and every experiment use 1,919. Nothing checked them. This script derives the
counts from the pinned manifest the experiments read and writes them as macros, so the sentence
can only print what the corpus holds.

HOW. Each page carries its urlscan scan id. Ids created since 2025 are UUIDv7, whose first 48 bits
are the scan's creation time in milliseconds, i.e. the capture time. 110 retrospective pages carry
older, non-v7 ids and no capture log row, so they are reported as undated rather than guessed.
Months are counted in Asia/Ho_Chi_Minh.

OUT:  papers/P3_multimodal/sections/gen_capture_window.tex
RUN:  python scripts/make_p3_capture_window.py
"""
import csv
import os
import sys
from collections import Counter
from datetime import datetime, timedelta, timezone

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(_HERE, "..", "..", "core", "lib"))
from genfile import write_generated, write_results  # noqa: E402

ROOT = os.path.abspath(os.path.join(_HERE, "..", "..", ".."))
MANIFEST = os.path.join(ROOT, "data", "interim", "content_manifest_vi.csv")
OUT_TEX = os.path.join(ROOT, "papers", "P3_multimodal", "sections", "gen_capture_window.tex")
TZ = timezone(timedelta(hours=7))
MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August",
          "September", "October", "November", "December"]


def scan_time(uuid: str):
    """UUIDv7 creation time, or None for any other id."""
    u = uuid.strip()
    if len(u) != 36 or u[14] != "7":
        return None
    ms = int(u.replace("-", "")[:12], 16)
    return datetime.fromtimestamp(ms / 1000, tz=timezone.utc).astimezone(TZ)


def main() -> None:
    with open(MANIFEST, encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    times = [scan_time(r["scan_uuid"]) for r in rows]
    dated = [t for t in times if t is not None]
    by_month = Counter((t.year, t.month) for t in dated)
    (y1, m1), n1 = by_month.most_common(1)[0]
    (y2, m2), n2 = by_month.most_common(2)[1]
    tail = len(dated) - n1 - n2
    earliest = min(dated)
    undated = len(times) - len(dated)
    macros = {
        "CWTotal": f"{len(rows):,}", "CWPeakN": f"{n1:,}", "CWPeak": f"{MONTHS[m1 - 1]} {y1}",
        "CWSecondN": f"{n2:,}", "CWSecond": f"{MONTHS[m2 - 1]} {y2}", "CWTailN": f"{tail:,}",
        "CWEarliest": f"{MONTHS[earliest.month - 1]} {earliest.year}", "CWUndatedN": f"{undated:,}",
    }
    write_results(os.path.join(ROOT, "data", "processed", "p3", "results", "capture_window.json"), {
        "total": len(rows), "peak": [y1, m1, n1], "second": [y2, m2, n2], "tail": tail,
        "earliest": [earliest.year, earliest.month], "undated": undated})
    for k, v in macros.items():
        print(f"{k:12s} {v}")
    text = "% generated by scripts/make_p3_capture_window.py — do not edit\n"
    text += "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in macros.items())
    write_generated(OUT_TEX, text)
    print(f"[+] {OUT_TEX}")


if __name__ == "__main__":
    main()
