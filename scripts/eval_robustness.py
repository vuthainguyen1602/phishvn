#!/usr/bin/env python3
"""
eval_robustness.py — Evaluate detector ROBUSTNESS against LLM-generated phishing.

Two things:
  1) Measure overall performance + split by clean/LLM + by EACH LLM (recall = catch rate).
     Input: one of
       --pred pred.csv         (columns: label, score[, gen_model, is_llm])   -- no GPU needed
       --model DIR --data d.csv (PhoBERT; the script computes score)          -- needs transformers/torch
  2) --make-loo DIR : generate LEAVE-ONE-LLM-OUT splits from data (train = all LLMs except 1, test = the
     held-out LLM) so you can train and test generalization to an unseen LLM.

RUN:
  python eval_robustness.py --pred preds.csv
  python eval_robustness.py --model models/phobert_sms --data data/processed/dataset_sms.csv
  python eval_robustness.py --make-loo data/loo --data data/processed/dataset_sms.csv
"""
from __future__ import annotations
import argparse, os
import numpy as np
import pandas as pd
from sklearn.metrics import f1_score, precision_score, recall_score, average_precision_score


def line(name, y, score, thr=0.5):
    pred = (np.asarray(score) >= thr).astype(int)
    msg = f"  [{name}] n={len(y)} "
    if len(set(y)) > 1:
        msg += (f"F1={f1_score(y,pred):.3f} P={precision_score(y,pred,zero_division=0):.3f} "
                f"R={recall_score(y,pred,zero_division=0):.3f} PR-AUC={average_precision_score(y,score):.3f}")
    else:  # only 1 class (e.g. LLM phishing only) -> report recall (catch rate)
        msg += f"recall(caught)={recall_score(y,pred,zero_division=0):.3f}"
    print(msg)


def score_with_model(model_dir, texts, maxlen=128, batch=32):
    import torch
    from transformers import AutoTokenizer, AutoModelForSequenceClassification
    tok = AutoTokenizer.from_pretrained(model_dir, use_fast=False)
    mdl = AutoModelForSequenceClassification.from_pretrained(model_dir).eval()
    out = []
    with torch.no_grad():
        for i in range(0, len(texts), batch):
            enc = tok(list(texts[i:i+batch]), truncation=True, padding=True,
                      max_length=maxlen, return_tensors="pt")
            prob = torch.softmax(mdl(**enc).logits, dim=1)[:, 1]
            out += prob.tolist()
    return out


def evaluate(df):
    df = df.copy()
    df["y"] = (df["label"] == "phishing").astype(int) if df["label"].dtype == object else df["label"]
    print("== Overall ==")
    line("all", df.y, df.score)
    if "is_llm" in df:
        for k, g in df.groupby(df["is_llm"].fillna(0).astype(int)):
            line("LLM" if k == 1 else "clean", g.y, g.score)
    if "gen_model" in df:
        print("== By each LLM (recall = detection rate of samples generated by that LLM) ==")
        for m, g in df[df.get("is_llm", 0) == 1].groupby("gen_model"):
            line(str(m), g.y, g.score)


def make_loo(df, outdir):
    os.makedirs(outdir, exist_ok=True)
    llm = df[df.get("is_llm", 0) == 1]
    real = df[df.get("is_llm", 0) != 1]
    models = sorted(llm["gen_model"].dropna().unique())
    if not models:
        raise SystemExit("No gen_model column/LLM set to create leave-one-LLM-out.")
    for held in models:
        train = pd.concat([real, llm[llm.gen_model != held]])
        test = llm[llm.gen_model == held]
        train.to_csv(os.path.join(outdir, f"train_wo_{held}.csv"), index=False)
        test.to_csv(os.path.join(outdir, f"test_{held}.csv"), index=False)
        print(f"[loo] held out '{held}': train={len(train)} test={len(test)}")
    print(f"-> {outdir} (train train_wo_X, test test_X to measure generalization to an unseen LLM)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pred"); ap.add_argument("--model"); ap.add_argument("--data")
    ap.add_argument("--make-loo")
    args = ap.parse_args()

    if args.make_loo:
        make_loo(pd.read_csv(args.data), args.make_loo); return

    if args.pred:
        df = pd.read_csv(args.pred)
    elif args.model and args.data:
        df = pd.read_csv(args.data)
        df["text"] = df["text"].fillna("").astype(str)
        df["score"] = score_with_model(args.model, df["text"].tolist())
    else:
        raise SystemExit("Need --pred, or --model + --data, or --make-loo + --data.")
    evaluate(df)


if __name__ == "__main__":
    main()
