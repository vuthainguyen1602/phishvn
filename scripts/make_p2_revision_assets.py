def mac(name: str, value) -> None:
    if name in MACROS:
        raise SystemExit(f"macro {name} defined twice")
    MACROS[name] = str(value)


def f3(x: float) -> str:
    return f"{x:.3f}"


def s3(x: float) -> str:
    v = round(float(x), 3)
    return f"{(v if v != 0 else 0.0):+.3f}"


def s4(x: float) -> str:
    v = round(float(x), 4)
    return f"{(v if v != 0 else 0.0):+.4f}"


def tn(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def pct(x: float, d: int = 1) -> str:
    return f"{100 * x:.{d}f}"


def read(path: str) -> pd.DataFrame | None:
    return pd.read_csv(path) if os.path.exists(path) else None


def write(name: str, body: str) -> None:
    from genfile import write_generated
    from p2_supp import article_refs
    write_generated(os.path.join(SEC, name),
                    "% generated by scripts/make_p2_revision_assets.py\n"
                    + article_refs(body.rstrip("\n"), name) + "\n")


def ci95(d: np.ndarray, test_frac: float = 0.30) -> tuple[float, float, dict]:
    """Mean difference with the corrected resampled t interval."""
    from scipy import stats
    t = corrected_paired_t(d, test_frac=test_frac)
    half = stats.t.ppf(0.975, t["k"] - 1) * t["se"] if t["se"] else 0.0
    return t["mean"] - half, t["mean"] + half, t


# --------------------------------------------------------------------------- protocol, primary
def protocol_primary() -> None:
    """R4.2 / R4.5: the guard- and prior-matched contrast as the primary protocol table, with the
    per-seed differences, corrected t, interval, and the domain-resampled interval."""
    g = read(os.path.join(PROC, "p2_temporal_strict_guarded_pm.csv"))
    boot = read(os.path.join(REV, "bootstrap.csv"))
    if g is None:
        write("tab_rev_protocol.tex", "% p2_temporal_strict_guarded_pm.csv absent")
        return
    lines = [
        "\\begin{table*}[t]\\centering",
        "\\caption{The protocol contrast on the dated rows, against the random control that carries"
        " the same registrable-domain guard and is scored at the same test prior. F1 at"
        " $\\tau = 0.5$, mean over five seeds; $\\Delta$ = phishing-temporal minus control, per"
        " seed and averaged; $t$, $p$ and the first interval are the corrected resampled $t$-test"
        " over seeds; the second interval resamples registrable domains of the test window (1{,}000"
        " replicates) on the validation-carved fits of Section~\\ref{ssec:operating}.}",
        "\\label{tab:protocol}",
        "\\small\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{lcccccccccc}\\toprule",
        "Family & Control & Temporal & \\multicolumn{5}{c}{$\\Delta$ by seed} & $\\Delta$ &"
        " $t$ ($p$) & 95\\% CI (seeds; domains) \\\\",
        "\\cmidrule(lr){4-8}",
        " & & & 0 & 1 & 2 & 3 & 4 & & & \\\\ \\midrule",
    ]
    deltas, n_neg_ci = {}, 0
    for f in ORDER:
        t = g[(g.family == f) & (g.protocol == "temporal_strict")].set_index("seed").F1.sort_index()
        r = g[(g.family == f) & (g.protocol == "random_same_rows_guarded")].set_index("seed").F1.sort_index()
        d = (t - r).to_numpy()
        lo, hi, st = ci95(d)
        deltas[f] = st["mean"]
        dom = ""
        if boot is not None:
            b = boot[(boot.contrast == "temporal_minus_random") & (boot.family == f)
                     & (boot.threshold == "p05")]
            if len(b):
                dom = f"; $[{b.lo.iloc[0]:+.3f}, {b.hi.iloc[0]:+.3f}]$"
                n_neg_ci += int(b.hi.iloc[0] < 0)
        lines.append(f"{NAME.get(f, f)} & {f3(r.mean())} & {f3(t.mean())} & "
                     + " & ".join(f"{x:+.3f}" for x in d)
                     + f" & {s3(st['mean'])} & ${st.get('t', 0):+.2f}$ (${fmt_p(st['p'])}$)"
                     + f" & $[{lo:+.3f}, {hi:+.3f}]${dom} \\\\")
    lines += ["\\bottomrule\\end{tabular}\\end{table*}"]
    write("tab_rev_protocol.tex", "\n".join(lines))
    mac("RevProtoMin", s3(min(deltas.values())))
    mac("RevProtoMax", s3(max(deltas.values())))
    mac("RevProtoWorst", NAME.get(min(deltas, key=deltas.get), min(deltas, key=deltas.get)).lower()
        .replace("lightgbm", "LightGBM"))
    if boot is not None:
        mac("RevProtoDomExcl", n_neg_ci)
        mac("RevProtoDomIncl", len(ORDER) - n_neg_ci)
        for proto, tag in (("temporal_strict", "Temp"), ("random_same_rows_guarded", "Rand")):
            b = boot[(boot.contrast == f"LogReg_minus_CatBoost_{proto}") & (boot.threshold == "p05")]
            mac(f"RevLRminusCB{tag}", s3(b.estimate.iloc[0]))
            mac(f"RevLRminusCB{tag}CI", f"$[{b.lo.iloc[0]:+.3f}, {b.hi.iloc[0]:+.3f}]$")
    lr = g[(g.family == "LogReg") & (g.protocol == "temporal_strict")].set_index("seed").F1.sort_index()
    cb = g[(g.family == "CatBoost") & (g.protocol == "temporal_strict")].set_index("seed").F1.sort_index()
    lo, hi, st = ci95((lr - cb).to_numpy())
    mac("RevLRCBSeedMean", s3(st["mean"]))
    mac("RevLRCBSeedCI", f"$[{lo:+.3f}, {hi:+.3f}]$")
    mac("RevLRCBSeedP", f"${fmt_p(st['p'])}$")
    mac("RevLRCBSeedWins", f"{st['wins']} of {st['k']}")


# --------------------------------------------------------------------------- forward cut-offs
def windows() -> None:
    """R1.1 / R1.5 / R2.4: the primary contrast at four forward cut-offs."""
    files = {c: os.path.join(PROC, "p2_temporal_strict_guarded_pm.csv") if c == 0.7
             else os.path.join(REV, f"windows_cut{c}.csv") for c in CUTS}
    if not all(os.path.exists(p) for p in files.values()):
        write("tab_rev_windows.tex", "% forward cut-off runs incomplete")
        return
    lines = [
        "\\begin{table}[t]\\centering",
        "\\caption{The protocol contrast at four forward cut-offs of the dated phishing rows (the"
        " share of them in training; $0.70$ is Table~\\ref{tab:protocol}): $\\Delta$F1 = phishing-temporal"
        " minus the guard- and prior-matched random control, mean over five seeds, and the"
        " logistic-regression minus CatBoost F1 under the temporal protocol.}",
        "\\label{tab:windows}",
        "\\small\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{l" + "c" * len(CUTS) + "}\\toprule",
        "Family & " + " & ".join(f"{c:.2f}" for c in CUTS) + " \\\\ \\midrule",
    ]
    per = {}
    for c, p in files.items():
        g = pd.read_csv(p)
        m = g.groupby(["family", "protocol"]).F1.mean().unstack()
        per[c] = (m["temporal_strict"] - m["random_same_rows_guarded"],
                  m.loc["LogReg", "temporal_strict"] - m.loc["CatBoost", "temporal_strict"])
    for f in ORDER:
        lines.append(f"{NAME.get(f, f)} & " + " & ".join(s3(per[c][0][f]) for c in CUTS) + " \\\\")
    lines.append("\\midrule LR $-$ CatBoost (temporal) & "
                 + " & ".join(s3(per[c][1]) for c in CUTS) + " \\\\")
    lines += ["\\bottomrule\\end{tabular}\\end{table}"]
    write("tab_rev_windows.tex", "\n".join(lines))
    allv = pd.concat([per[c][0] for c in CUTS])
    mac("RevWinMin", s3(allv.min()))
    mac("RevWinMax", s3(allv.max()))
    # count on the values as Table tab:windows prints them, so a reader counting the table agrees
    mac("RevWinNeg", f"{int(sum((per[c][0].round(3) < 0).sum() for c in CUTS))} of "
                     f"{len(CUTS) * len(ORDER)}")
    mac("RevWinLRCBMin", s3(min(per[c][1] for c in CUTS)))
    mac("RevWinLRCBMax", s3(max(per[c][1] for c in CUTS)))
    mac("RevWinLRCBPos", f"{sum(per[c][1] > 0 for c in CUTS)} of {len(CUTS)}")


