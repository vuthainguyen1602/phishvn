def label_noise() -> None:
    """R2.5 / R1.13: the protocol contrast under bronze label-error scenarios."""
    n = read(os.path.join(REV, "label_noise.csv"))
    if n is None:
        write("tab_rev_labelnoise.tex", "% label-error scenarios absent")
        return
    f1 = n[n.metric == "f1"].pivot_table(index=["rate", "mode"], columns="family", values="delta_proto")
    base = read(os.path.join(REV, "operating.csv"))
    lines = [
        "\\begin{table}[t]\\centering",
        "\\caption{The protocol contrast ($\\Delta$F1 at $\\tau = 0.5$, temporal minus the matched"
        " control; validation-carved fits) when a share of the bronze-tier phishing rows in each"
        " test window are in truth benign: chosen at random (mean of 200 draws) or, as a worst"
        " case, the ones each model scores lowest. $12.1\\%$ is the audited positive-label error"
        " rate. Each entry is the mean over the five seeds of the per-seed step.}",
        "\\label{tab:labelnoise_sim}",
        "\\small\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{ll" + "c" * len(ORDER) + "}\\toprule",
        "Share & Choice & " + " & ".join(NAME.get(f, f).replace("Logistic regression", "LR")
                                         .replace("Random forest", "RF") for f in ORDER)
        + " \\\\ \\midrule",
    ]
    for (rate, mode), row in f1.iterrows():
        lines.append(f"{pct(rate)}\\% & {mode.replace('_', ' ')} & "
                     + " & ".join(s3(row[f]) for f in ORDER) + " \\\\")
    lines += ["\\bottomrule\\end{tabular}\\end{table}"]
    write("tab_rev_labelnoise.tex", "\n".join(lines))
    rnd = f1.xs("random", level="mode")
    worst = f1.xs("lowest_score", level="mode")
    mac("RevNoiseRandMaxShift", f3(float((rnd - rnd.iloc[0]).abs().to_numpy().max())))
    mac("RevNoiseRandSignKept", "all" if bool(((rnd < 0) == (rnd.iloc[0] < 0)).all().all()) else "not all")
    w12 = worst.loc[0.121]
    mac("RevNoiseWorstPos", f"{int((w12 > 0).sum())} of {len(ORDER)}")
    w5 = worst.loc[0.05]
    mac("RevNoiseWorstFivePos", f"{int((w5 > 0).sum())} of {len(ORDER)}")
    noise_ordering()


def noise_ordering() -> None:
    """Whether the family ordering under the temporal protocol survives label error, with the
    SAME rows relabelled for every family (analyse_p2_noise_ordering.py)."""
    o = read(os.path.join(REV, "noise_ordering.csv"))
    if o is None:
        return
    m = o.groupby(["rate", "mode", "family"]).f1.mean().unstack()
    lrcb = m["LogReg"] - m["CatBoost"]
    rnd = lrcb.xs("random", level="mode")
    hard = lrcb.xs("hard", level="mode")
    mac("RevOrdRandLRCBMin", s3(rnd.min()))
    mac("RevOrdRandLRCBMax", s3(rnd.max()))
    rnd_top = [m.loc[(r, "random")].idxmax() for r in rnd.index]
    mac("RevOrdRandLRTop", "every" if all(t == "LogReg" for t in rnd_top) else "not every")
    mac("RevOrdHardFiveLRCB", s3(hard.loc[0.05]))
    mac("RevOrdHardTwelveLRCB", s3(hard.loc[0.121]))
    mac("RevOrdHardTwentyLRCB", s3(hard.loc[0.20]))
    row = m.loc[(0.121, "hard")].sort_values(ascending=False)
    rank = list(row.index).index("LogReg") + 1
    mac("RevOrdHardTwelveLRRank", "last of seven" if rank == len(row) == 7 else f"{rank} of {len(row)}")
    mac("RevOrdHardTwelveLRFOne", f3(row["LogReg"]))
    others = row.drop("LogReg")
    mac("RevOrdHardTwelveOthersMin", f3(others.min()))
    mac("RevOrdHardTwelveOthersMax", f3(others.max()))


