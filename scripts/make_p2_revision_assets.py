def hpo_space() -> None:
    """R4.9 / R1.7: every family's search space, read from the search code itself, so the table
    cannot drift from what was searched."""
    import importlib.util
    spec = importlib.util.spec_from_file_location("hpo_gwo", os.path.join(_HERE, "hpo_gwo.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    space = mod.SPACE
    missing = [f for f in ORDER if f not in space]
    if missing:
        raise SystemExit(f"hpo_gwo.SPACE has no entry for {missing}")

    def rng(lo, hi, kind):
        if kind == "logfloat":
            return f"$10^{{[{lo:g},\\,{hi:g}]}}$"
        if kind == "int":
            return f"{int(lo)}--{int(hi)}"
        return f"{lo:g}--{hi:g}"

    lines = [
        "\\begin{table}[t]\\centering",
        "\\caption{The search space of every family in the tuning arm of Table~\\ref{tab:hpoall},"
        " as the search code defines it. The spaces differ in dimension, and both searches get"
        " the same 54 evaluations whatever the dimension, so a one-parameter space is searched"
        " far more densely than a five-parameter one.}",
        "\\label{tab:hpospace}",
        "\\small",
        "\\begin{tabular}{lcp{0.62\\linewidth}}\\toprule Family & Dim. & Parameters and ranges"
        " \\\\ \\midrule",
    ]
    for f in ORDER:
        params = "; ".join(f"{PARAM_NAME.get(n, n.replace('_', ' '))} {rng(lo, hi, k)}"
                           for n, lo, hi, k in space[f])
        lines.append(f"{NAME.get(f, f)} & {len(space[f])} & {params} \\\\")
    lines += ["\\bottomrule\\end{tabular}\\end{table}"]
    write("tab_rev_hpospace.tex", "\n".join(lines))
    dims = [len(space[f]) for f in ORDER]
    mac("RevHPODimMin", min(dims))
    mac("RevHPODimMax", max(dims))


# --------------------------------------------------------------------------- attribution stability
def attribution() -> None:
    """R1.9 / R2.9: is the TreeSHAP ranking stable across families, seeds and corpora?"""
    a = read(os.path.join(REV, "attribution_stability.csv"))
    if a is None:
        write("tab_rev_attr.tex", "% attribution stability run absent")
        return
    from scipy.stats import spearmanr
    import itertools
    out, tops = {}, {}
    for corpus, g in a.groupby("corpus"):
        piv = g.pivot_table(index=["family", "seed"], columns="feature", values="mean_abs_shap")
        fams, seeds = sorted(g.family.unique()), sorted(g.seed.unique())
        sr = [spearmanr(piv.loc[(f, x)], piv.loc[(f, y)]).statistic
              for f in fams for x, y in itertools.combinations(seeds, 2)]
        fr = [spearmanr(piv.loc[(x, s)], piv.loc[(y, s)]).statistic
              for s in seeds for x, y in itertools.combinations(fams, 2)]
        out[corpus] = (float(np.nanmean(sr)), float(np.nanmean(fr)))
        mean = g.groupby("feature").mean_abs_shap.mean().sort_values(ascending=False)
        tops[corpus] = list(mean.index[:3])
    mac("RevAttrSeedRhoMin", f"{min(v[0] for v in out.values()):.2f}")
    mac("RevAttrFamRhoMin", f"{min(v[1] for v in out.values()):.2f}")
    mac("RevAttrFamRhoMax", f"{max(v[1] for v in out.values()):.2f}")
    vn = tops.get("PhishVN", [])
    mac("RevAttrVNTop", ", ".join(f"\\texttt{{{t.replace('_', chr(92) + '_')}}}" for t in vn))
    shared = set.intersection(*(set(v) for v in tops.values()))
    mac("RevAttrSharedTop", len(shared))
    lines = ["\\begin{table}[t]\\centering",
             "\\caption{TreeSHAP attribution across the five tree families and three seeds on each"
             " corpus's in-distribution cell: mean Spearman correlation of the importance vectors"
             " between seeds (same family) and between families (same seed), and the three features"
             " with the largest mean $|$SHAP$|$.}",
             "\\label{tab:attrstab}", "\\small",
             "\\begin{tabular}{lccl}\\toprule Corpus & $\\rho$ seeds & $\\rho$ families & Top three \\\\ \\midrule"]
    for corpus in out:
        lines.append(f"{corpus} & {out[corpus][0]:.2f} & {out[corpus][1]:.2f} & "
                     + ", ".join(f"\\texttt{{{t.replace('_', chr(92) + '_')}}}" for t in tops[corpus]) + " \\\\")
    lines += ["\\bottomrule\\end{tabular}\\end{table}"]
    write("tab_rev_attr.tex", "\n".join(lines))


