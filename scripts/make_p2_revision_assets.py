def operating() -> None:
    """R1.4 / R1.11: calibration and deployable operating points under both protocols."""
    op, cal = read(os.path.join(REV, "operating.csv")), read(os.path.join(REV, "calibration.csv"))
    if op is None or cal is None:
        write("tab_rev_operating.tex", "% operating-point analysis absent")
        return
    o = op.groupby(["protocol", "family"]).mean(numeric_only=True)
    c = cal.groupby(["protocol", "family"]).mean(numeric_only=True)
    lines = [
        "\\begin{table*}[t]\\centering",
        "\\caption{Operating points a practitioner could fix without the test window. Each model is"
        " fitted on its training window minus a validation slice; $\\tau^*$ maximises F1 on that"
        " slice. FP/10k = false positives per 10{,}000 benign test URLs at $\\tau^*$; Prec@1\\% ="
        " precision at $\\tau^*$ if phishing were $1\\%$ of traffic (from the same TPR and FPR);"
        " R@FPR$\\le$1\\% = recall at the threshold that lets $1\\%$ of the validation benign rows"
        " through. Brier and ECE (15 bins) on the test window. Mean over five seeds.}",
        "\\label{tab:operating}",
        "\\small\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{l" + "cccccc" * 2 + "}\\toprule",
        " & \\multicolumn{6}{c}{Random (guard- and prior-matched)} & \\multicolumn{6}{c}{Phishing-temporal} \\\\",
        "\\cmidrule(lr){2-7}\\cmidrule(lr){8-13}",
        "Family" + " & F1@$\\tau^*$ & FP/10k & Prec@1\\% & R@FPR$\\le$1\\% & Brier & ECE" * 2
        + " \\\\ \\midrule",
    ]
    for f in ORDER:
        cells = []
        for proto in ("random_same_rows_guarded", "temporal_strict"):
            r, k = o.loc[(proto, f)], c.loc[(proto, f)]
            cells += [f3(r["f1"]), f"{r['fp_per_10k_benign']:,.0f}".replace(",", "{,}"),
                      f3(r["precision_at_0.01"]), f3(r["recall_at_fpr0.01"]),
                      f3(k["brier"]), f3(k["ece"])]
        lines.append(f"{NAME.get(f, f)} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule\\end{tabular}\\end{table*}"]
    write("tab_rev_operating.tex", "\n".join(lines))
    t = o.loc["temporal_strict"]
    mac("RevOpFPMin", tn(int(round(t.fp_per_10k_benign.min()))))
    mac("RevOpFPMax", tn(int(round(t.fp_per_10k_benign.max()))))
    mac("RevOpFPRMin", pct(t.fpr.min(), 0))
    mac("RevOpFPRMax", pct(t.fpr.max(), 0))
    mac("RevOpPrecOneMax", f3(t["precision_at_0.01"].max()))
    mac("RevOpPrecFiveMax", f3(t["precision_at_0.05"].max()))
    mac("RevOpPrecTenMax", f3(t["precision_at_0.1"].max()))
    mac("RevOpRecOneMin", f3(t["recall_at_fpr0.01"].min()))
    mac("RevOpRecOneMax", f3(t["recall_at_fpr0.01"].max()))
    mac("RevOpRecTenthMax", f3(t["recall_at_fpr0.001"].max()))
    mac("RevOpRealFPRMax", pct(t["realised_fpr_at_fpr0.01"].max(), 2))
    ct, cr = c.loc["temporal_strict"], c.loc["random_same_rows_guarded"]
    tau = op.groupby("protocol").tau_val.mean()
    mac("RevTauRand", f3(tau["random_same_rows_guarded"]))
    mac("RevTauTemp", f3(tau["temporal_strict"]))
    mac("RevCalECEWorse", f"{int((ct.ece > cr.ece).sum())} of {len(ORDER)}")
    mac("RevCalBrierWorse", f"{int((ct.brier > cr.brier).sum())} of {len(ORDER)}")
    mac("RevCalECETempMin", f3(ct.ece.min()))
    mac("RevCalECETempMax", f3(ct.ece.max()))
    mac("RevCalECERandMin", f3(cr.ece.min()))
    mac("RevCalECERandMax", f3(cr.ece.max()))


